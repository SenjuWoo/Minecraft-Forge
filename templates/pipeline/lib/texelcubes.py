"""Cube lists for selective render passes: gen/<Mob>Cubes.java.

A glow layer or a timed overlay (wet, flush, dirt, damage) redraws the model with another texture. GeckoLib's own
layers redraw every cube, and most of them carry no texel of that texture: in two finished mobs the glow pass cost
1.55 ms per instance until it drew only the cubes with glow texels (1.03 ms), and three overlays fell from 3.45 ms
to 1.17 ms the same way. This step writes, for every layer texture, the cubes that carry at least one opaque texel
of it, and the kit's CubePasses resolves them to the baked cubes at runtime.

A layer texture is any textures/entity/<geo>_<suffix>.png with the size of <geo>.png, where <geo> is a geometry of
this mob (<mob>, <mob>_shell, ...) and <geo>_<suffix> is not itself a geometry. The UV test texture and labPBR maps
(_uvtest, _n, _s) are skipped. Constants are named after the suffix (GLOWMASK, WET) and, for a second geometry,
prefixed with its name (SHELL_GLOWMASK). Rows read "bone:cube,cube,..." in geo.json order, the order GeckoLib bakes.

Run it after every step that writes a layer texture (`all` runs it after `texture`; put it after your own overlay
command in mob/commands.py ALL_ORDER).
"""
from __future__ import annotations

import json

import numpy as np
from PIL import Image

from . import paths

SKIP = {"uvtest", "n", "s"}


def geometries() -> list[str]:
    return sorted(p.name[: -len(".geo.json")] for p in paths.GEO.glob(f"{paths.MOB}*.geo.json")) if paths.GEO.is_dir() else []


def layers() -> list[tuple[str, str, str]]:
    """(geometry, suffix, constant name) for every layer texture present."""
    geos = geometries()
    out = []
    for geo in geos:
        base = paths.TEX / f"{geo}.png"
        if not base.is_file():
            continue
        size = Image.open(base).size
        for path in sorted(paths.TEX.glob(f"{geo}_*.png")):
            stem = path.stem
            suffix = stem[len(geo) + 1:]
            if stem in geos or suffix in SKIP or not suffix or Image.open(path).size != size:
                continue
            if any(stem.startswith(other + "_") and len(other) > len(geo) for other in geos):
                continue                       # belongs to a longer geometry name (mob_shell_glowmask vs mob)
            prefix = geo[len(paths.MOB):].lstrip("_")
            name = (prefix + "_" + suffix if prefix else suffix).upper()
            out.append((geo, suffix, "".join(ch if ch.isalnum() else "_" for ch in name)))
    return out


def cube_rows(geo: str, alpha: np.ndarray) -> dict[str, list[int]]:
    data = json.loads((paths.GEO / f"{geo}.geo.json").read_text(encoding="utf-8"))
    hits: dict[str, list[int]] = {}
    for bone in data["minecraft:geometry"][0]["bones"]:
        for i, cube in enumerate(bone.get("cubes", [])):
            for face in cube.get("uv", {}).values():
                u, v = int(face["uv"][0]), int(face["uv"][1])
                w = max(1, int(np.ceil(face["uv_size"][0])))
                h = max(1, int(np.ceil(face["uv_size"][1])))
                if alpha[v:v + h, u:u + w].any():
                    hits.setdefault(bone["name"], []).append(i)
                    break
    return hits


def build() -> dict[str, dict[str, list[int]]]:
    out = {}
    for geo, suffix, const in layers():
        alpha = np.asarray(Image.open(paths.TEX / f"{geo}_{suffix}.png").convert("RGBA"))[..., 3] > 0
        out[const] = cube_rows(geo, alpha)
    return out


def java(found: dict[str, dict[str, list[int]]]) -> str:
    cls = paths.PASCAL + "Cubes"
    nl = "\n"
    lines = ["// GENERATED by asset-pipeline/lib/texelcubes.py - do not edit; rerun `build_assets.py cubes`.",
             f"package {paths.PACKAGE}.gen;", "",
             "/** Per layer texture: the cubes that carry any of its texels, as \"bone:cube,cube,...\" (kit CubePasses). */",
             f"public final class {cls} {{", f"    private {cls}() {{}}"]
    for const, hits in found.items():
        rows = ("," + nl + "            ").join('"' + bone + ":" + ",".join(map(str, ix)) + '"' for bone, ix in hits.items())
        lines += ["", f"    /** {sum(map(len, hits.values()))} cubes in {len(hits)} bones. */",
                  f"    public static final String[] {const} = {{" + (nl + "            " + rows if rows else "") + "};"]
    lines.append("}")
    return nl.join(lines) + nl


def run(args) -> int:
    found = build()
    paths.write_text(paths.JAVA_GEN / f"{paths.PASCAL}Cubes.java", java(found))
    for const, hits in found.items():
        print(f"cubes {const}: {sum(map(len, hits.values()))} cube(s) in {len(hits)} bone(s)")
    if not found:
        print("cubes: no layer texture (glowmask or overlay) yet")
    return 0


def validate(args) -> int:
    errs = []
    for const, hits in build().items():
        if not hits:
            errs.append(f"{const}: the texture has no opaque texel on any cube (a layer that draws nothing)")
    for e in errs:
        print("CUBES ERROR:", e)
    print(f"cubes validate: {len(errs)} error(s)")
    return 1 if errs else 0
