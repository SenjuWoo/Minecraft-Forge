"""Sounds: mob/sounds.py EVENTS + the OGG files present -> assets/<mod>/sounds.json, subtitle lang keys and
gen/<Mob>Sounds.java (self-registering SoundEvents and each event's longest file in ticks, for talk time and
queues). Event ids are namespaced by the mob: <mob>.<event>; files live in assets/<mod>/sounds/<mob>/.
"""
from __future__ import annotations

import json
import shutil
import subprocess

from . import paths

FOLDER = paths.SOUNDS / paths.MOB


def duration(path) -> float:
    if not shutil.which("ffprobe"):
        return 0.0
    r = subprocess.run(["ffprobe", "-v", "quiet", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
                       capture_output=True, text=True)
    try:
        return float(r.stdout.strip())
    except ValueError:
        return 0.0


def collect():
    from mob import sounds as MS
    found, missing = {}, []
    for event, (subtitle, pattern, options) in MS.EVENTS.items():
        files = sorted(FOLDER.glob(pattern + ".ogg")) if FOLDER.is_dir() else []
        if files:
            found[event] = (subtitle, files, options)
        else:
            missing.append(event)
    return found, missing


def java(found) -> str:
    cls = paths.PASCAL + "Sounds"
    lines = ["// GENERATED by asset-pipeline/lib/soundtools.py - do not edit; change mob/sounds.py and rerun `build_assets.py sounds`.",
             f"package {paths.PACKAGE}.gen;", "", "import java.util.Map;", "import net.minecraft.core.registries.Registries;",
             "import net.minecraft.resources.ResourceLocation;", "import net.minecraft.sounds.SoundEvent;",
             "import net.neoforged.bus.api.SubscribeEvent;", "import net.neoforged.fml.common.EventBusSubscriber;",
             "import net.neoforged.neoforge.registries.DeferredHolder;", "import net.neoforged.neoforge.registries.RegisterEvent;", "",
             f"/** Sound events of the {paths.MOB} mob; registers itself on the mod bus. */",
             f'@EventBusSubscriber(modid = "{paths.MOD}")',
             f"public final class {cls} {{", f"    private {cls}() {{}}", ""]
    for event in found:
        const = event.upper().replace(".", "_")
        lines.append(f"    public static final DeferredHolder<SoundEvent, SoundEvent> {const} = "
                     f'DeferredHolder.create(Registries.SOUND_EVENT, ResourceLocation.fromNamespaceAndPath("{paths.MOD}", "{paths.MOB}.{event}"));')
    lines += ["", "    @SubscribeEvent", "    public static void register(RegisterEvent event) {"]
    for name in found:
        rl = f'ResourceLocation.fromNamespaceAndPath("{paths.MOD}", "{paths.MOB}.{name}")'
        lines.append(f"        event.register(Registries.SOUND_EVENT, {rl}, () -> SoundEvent.createVariableRangeEvent({rl}));")
    lines += ["    }", "", "    /** Longest file of each event in game ticks (0 when ffprobe was not available at build time). */",
              "    public static final Map<String, Integer> LENGTH_TICKS = Map.ofEntries("]
    rows = [f'            Map.entry("{name}", {int(max((duration(f) for f in files), default=0.0) * 20 + 0.999)})'
            for name, (_, files, _) in found.items()]
    lines.append(",\n".join(rows) + ");" if rows else "    );")
    lines.append("}")
    return "\n".join(lines) + "\n"


def run(args) -> int:
    found, missing = collect()
    target = paths.ASSETS / "sounds.json"
    existing = json.loads(target.read_text(encoding="utf-8-sig")) if target.exists() else {}
    prefix = paths.MOB + "."
    merged = {k: v for k, v in existing.items() if not k.startswith(prefix)}
    lang_path = paths.ASSETS / "lang/en_us.json"
    lang = json.loads(lang_path.read_text(encoding="utf-8-sig")) if lang_path.exists() else {}
    lang = {k: v for k, v in lang.items() if not k.startswith(f"subtitles.{paths.MOD}.{prefix}")}
    for event, (subtitle, files, options) in found.items():
        sounds = []
        for f in files:
            entry = {"name": f"{paths.MOD}:{paths.MOB}/{f.stem}"} | {k: v for k, v in options.items()}
            sounds.append(entry if len(entry) > 1 else entry["name"])
        key = f"subtitles.{paths.MOD}.{prefix}{event}"
        merged[prefix + event] = {"subtitle": key, "sounds": sounds}
        lang[key] = subtitle
    java_path = paths.JAVA_GEN / f"{paths.PASCAL}Sounds.java"
    if found:
        paths.write_json(target, merged)
        paths.write_json(lang_path, lang)
        paths.write_text(java_path, java(found))
    else:
        if merged != existing:
            paths.write_json(target, merged)
        if java_path.exists():
            java_path.unlink()
    from mob import sounds as MS
    planned = list(getattr(MS, "PLANNED", {}))
    print(f"sounds: {len(found)} event(s) with files, {len(missing)} without" + (f" ({', '.join(missing[:8])})" if missing else "")
          + (f"; {len(planned)} planned" if planned else ""))
    return 0


def validate(args) -> int:
    found, missing = collect()
    errs = [f"event {m} has no OGG file in {FOLDER}" for m in missing]
    if found:
        r = paths.forge("audio-check", str(paths.PROJECT))
        try:
            report = json.loads(r.stdout)
            for problem in report.get("problems", [])[:12]:
                errs.append(f"audio-check: {problem}")
            print(f"audio-check: {len(report.get('problems', []))} problem(s)")
        except json.JSONDecodeError:
            errs.append(f"audio-check did not run (exit {r.returncode})")
    for e in errs:
        print("SOUND ERROR:", e)
    print(f"sounds validate: {len(errs)} error(s)")
    return 1 if errs else 0
