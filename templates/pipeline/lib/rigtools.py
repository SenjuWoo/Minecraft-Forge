"""Rig: mob/rig.py -> build/rig_manifest.json (read by the model, animation and texture validators) and
gen/<Mob>Rig.java (bone names, swap groups, procedural set, springs for the SpringBones kit)."""
from __future__ import annotations

import json

from mob import rig as R

from . import paths

GAINS = paths.PIPE / "spring_gains.json"


def mirror(entries):
    """Expand *_L entries into _l and _r with the pivot x mirrored. An optional 4th element is the bone's rest
    rotation in Blockbench degrees (rx, ry, rz); the mirrored side gets (rx, -ry, -rz)."""
    out = []
    for entry in entries:
        name, parent, pivot = entry[:3]
        rot = tuple(float(v) for v in entry[3]) if len(entry) > 3 else (0.0, 0.0, 0.0)
        if "_L" in name:
            for side, sx in (("l", 1), ("r", -1)):
                n = name.replace("_L", "_" + side)
                p = parent.replace("_L", "_" + side) if parent else None
                out.append((n, p, (pivot[0] * sx + 0.0, pivot[1], pivot[2]), (rot[0], rot[1] * sx + 0.0, rot[2] * sx + 0.0)))
        else:
            out.append((name, parent.replace("_L", "_l") if parent else None, pivot, rot))
    return out


def bones():
    return mirror(R.BONES)


def procedural(names) -> list[str]:
    return [n for n in names if n.endswith("_phys") or n in R.EXTRA_PROCEDURAL]


def gains() -> dict:
    return json.loads(GAINS.read_text(encoding="utf-8")) if GAINS.exists() else {}


def manifest() -> dict:
    bl = bones()
    names = [b[0] for b in bl]
    tuned = gains()
    springs = []
    for bone, k, c, clamp, r, gain in R.SPRINGS:
        rx = -r[0] if bone.endswith("_r_phys") or "_r_" in bone else r[0]
        springs.append({"bone": bone, "k": k, "c": c, "clamp_rot_deg": clamp[0], "clamp_pos_px": clamp[1], "clamp_scale": clamp[2],
                        "r": [rx + 0.0, r[1], r[2]], "gain": round(float(tuned.get(bone, gain)), 4)})
    return {"bones": [{"name": n, "parent": p, "pivot": list(pv), "rotation": list(rt)} for n, p, pv, rt in bl],
            "procedural": procedural(names),
            "swap_groups": R.SWAP_GROUPS, "springs": springs, "look": R.LOOK, "legs": R.LEGS}


def java(m: dict) -> str:
    cls = paths.PASCAL + "Rig"
    lines = ["// GENERATED by asset-pipeline/lib/rigtools.py - do not edit; change mob/rig.py and rerun `build_assets.py rig`.",
             f"package {paths.PACKAGE}.gen;", "", f"import {paths.PACKAGE}.kit.SpringBones;", "import java.util.List;",
             "import java.util.Set;", "", f"/** Bone names, swap groups, procedural set and spring constants of the {paths.MOB} rig. */",
             f"public final class {cls} {{", f"    private {cls}() {{}}", ""]
    for b in m["bones"]:
        lines.append(f'    public static final String {b["name"].upper()} = "{b["name"]}";')
    lines += ["", "    /** The bone the head look is added to; no clip keys it. */", f"    public static final String LOOK = {m['look'].upper()};", ""]
    for g, members in m["swap_groups"].items():
        lines.append(f"    public static final List<String> SWAP_{g.upper()} = List.of({', '.join(x.upper() for x in members)});")
    lines += ["", "    /** Bones code writes every frame; no clip keys them. */",
              f"    public static final Set<String> PROCEDURAL = Set.of({', '.join(x.upper() for x in m['procedural'])});", "",
              "    public static final List<SpringBones.Def> SPRINGS = List.of("]
    rows = [f'            new SpringBones.Def({s["bone"].upper()}, {s["k"]}f, {s["c"]}f, {float(s["clamp_rot_deg"])}f, '
            f'{float(s["clamp_pos_px"])}f, {float(s["clamp_scale"])}f, {s["r"][0]}f, {s["r"][1]}f, {s["r"][2]}f, {s["gain"]}f)'
            for s in m["springs"]]
    lines.append(",\n".join(rows) + ");")
    lines.append("}")
    return "\n".join(lines) + "\n"


def run(args) -> int:
    m = manifest()
    paths.write_json(paths.BUILD / "rig_manifest.json", m)
    paths.write_text(paths.JAVA_GEN / f"{paths.PASCAL}Rig.java", java(m))
    print(f"rig: {len(m['bones'])} bones, {len(m['procedural'])} procedural, {len(m['swap_groups'])} swap groups, {len(m['springs'])} springs")
    return 0


def load_manifest() -> dict:
    return json.loads((paths.BUILD / "rig_manifest.json").read_text(encoding="utf-8"))


def check_clip_bones(m: dict, anim_json: dict) -> list[str]:
    """Shared with the animation validator: unknown bones and keyed procedural bones are errors."""
    names = {b["name"] for b in m["bones"]}
    proc = set(m["procedural"])
    errs = []
    for clip, body in anim_json.get("animations", {}).items():
        for bone in body.get("bones", {}):
            if bone not in names:
                errs.append(f"{clip}: unknown bone {bone}")
            elif bone in proc:
                errs.append(f"{clip}: keys procedural bone {bone}")
    return errs


def validate(args) -> int:
    m = load_manifest()
    errs = []
    names = [b["name"] for b in m["bones"]]
    if len(set(names)) != len(names):
        errs.append("duplicate bone names")
    seen = set()
    for b in m["bones"]:
        if b["parent"] and b["parent"] not in seen:
            errs.append(f"{b['name']}: parent {b['parent']} unknown or listed later")
        seen.add(b["name"])
    parent = {b["name"]: b["parent"] for b in m["bones"]}
    for g, members in m["swap_groups"].items():
        for x in members:
            if x not in seen:
                errs.append(f"swap group {g}: unknown bone {x}")
        if len({parent.get(x) for x in members}) != 1:
            errs.append(f"swap group {g}: members do not share one parent")
    for s in m["springs"]:
        if s["bone"] not in seen or s["bone"] not in m["procedural"]:
            errs.append(f"spring {s['bone']}: not a procedural bone")
        elif parent.get(s["bone"]) is None:
            errs.append(f"spring {s['bone']}: a sprung bone needs a parent (its anchor)")
    if m["look"] not in m["procedural"]:
        errs.append(f"look bone {m['look']} must be procedural (list it in EXTRA_PROCEDURAL)")
    for leg in m["legs"]:
        if leg not in seen:
            errs.append(f"LEGS names an unknown bone {leg}")
    # self-test of the clip validator: a clip keying an unknown and a procedural bone must fail twice
    if m["procedural"]:
        probe = check_clip_bones(m, {"animations": {"probe": {"bones": {"no_such_bone": {}, m["procedural"][0]: {}, names[0]: {}}}}})
        if len(probe) != 2:
            errs.append(f"clip validator self-test failed: {probe}")
    src = (paths.JAVA_GEN / f"{paths.PASCAL}Rig.java").read_text(encoding="utf-8")
    for n in names:
        if f'"{n}"' not in src:
            errs.append(f"{paths.PASCAL}Rig.java lacks {n}")
    for e in errs:
        print("RIG ERROR:", e)
    print(f"rig validate: {len(errs)} error(s)")
    return 1 if errs else 0
