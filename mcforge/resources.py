"""Version facts read from the game: pack formats and resource/data folder names.

``mcforge/data/minecraft_versions.json`` is generated by scripts/build_facts.py
from each release's own client JAR. Folder names changed several times (plural
data folders until 1.20.6, item definitions from 1.21.4, equipment assets from
1.21.2), so generators ask here instead of assuming one layout.
"""
from __future__ import annotations

from functools import lru_cache
import json
from pathlib import Path

DATA = Path(__file__).resolve().parent / "data" / "minecraft_versions.json"


def version_key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split(".") if part.isdigit())


@lru_cache(maxsize=1)
def _table() -> dict:
    return json.loads(DATA.read_text(encoding="utf-8"))["versions"]


def known_versions() -> list[str]:
    return sorted(_table(), key=version_key)


def facts(minecraft: str) -> dict:
    """Facts for one release; an unlisted version borrows the nearest older release and says so."""
    table = _table()
    if minecraft in table:
        return dict(table[minecraft], minecraft=minecraft, exact=True)
    older = [version for version in table if version_key(version) <= version_key(minecraft)]
    if not older:
        raise ValueError(f"No recorded facts at or before Minecraft {minecraft}; the table starts at {known_versions()[0]}")
    nearest = max(older, key=version_key)
    return dict(table[nearest], minecraft=minecraft, exact=False, borrowed_from=nearest)


def pack_mcmeta(minecraft: str, kind: str, description: str) -> dict:
    """pack.mcmeta for a resource or data pack, in the form that release reads."""
    row = facts(minecraft)
    major, minor = row["resource_pack_format" if kind == "resource" else "data_pack_format"]
    raw = row.get("pack_version_raw")
    if isinstance(raw, dict) and ("resource_major" in raw or "data_major" in raw):
        # Releases with major/minor pack versions read min_format/max_format instead of pack_format.
        version = [major, minor] if minor else major
        return {"pack": {"description": description, "min_format": version, "max_format": version}}
    return {"pack": {"description": description, "pack_format": major}}
